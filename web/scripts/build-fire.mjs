// Build one classic, dependency-free progressive enhancement from the same pure
// model tested by Node. No client framework, runtime compiler or network calls.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { Script } from 'node:vm';
const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('src/features/fire/model.ts', root), 'utf8');
const { outputText } = ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, removeComments: true },
});
if (/\brequire\s*\(/.test(outputText)) throw new Error('The FIRE model must remain runtime-dependency-free.');
const ui = readFileSync(new URL('src/enhancements/fire-calculator.js', root), 'utf8');
const output = new URL('public/fire-calculator.js', root);
const bundle = `// Generated by scripts/build-fire.mjs; edit model/enhancement sources instead.\n(() => {\nconst fireModel = (() => { const exports = {};\n${outputText}\nreturn exports; })();\n${ui}\n})();\n`;
// Syntax-check the exact browser artifact, not just its source modules.
new Script(bundle, { filename: 'fire-calculator.js' });
writeFileSync(output, bundle);
console.log(`Built ${fileURLToPath(output)} from the tested FIRE model.`);
